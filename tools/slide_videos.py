def fill(scenes):
    """В сцены, где снизу пусто, добавляем фото Оксаны ровно в свободное место."""
    pool = [1, 2, 3, 5]
    for i, sc in enumerate(scenes):
        els = sc["els"]; kinds = [e["k"] for e in els]
        for e in els:
            if e["k"] in ("pills", "cross") and len(e["items"]) >= 3:
                e.setdefault("size", 62); e["step"] = 195; e["y"] = min(e.get("y", 760), 790)
        if "photo" in kinds or "steps" in kinds or "bars" in kinds: continue
        bottom = 0
        for e in els:
            k = e["k"]
            if k in ("pills", "cross"):
                y = e.get("y", 760); n = len(e["items"]); bottom = max(bottom, y + (n - 1) * e.get("step", 150) + 60)
            elif k == "cards2": bottom = max(bottom, e.get("y", 860) + 240)
            elif k == "msg": bottom = max(bottom, e.get("y", 820) + 90)
        h = min(420, 1330 - (bottom + 40))
        if h < 260: continue
        used = {e.get("pid") for j in (i - 1, i + 1) if 0 <= j < len(scenes) for e in scenes[j]["els"]}
        pid = next((x for x in pool if x not in used), pool[0]); pool.append(pool.pop(0))
        els.append({"k": "photo", "pid": pid, "x": 540, "y": int(bottom + 40 + h / 2), "w": int(h * 0.92), "h": int(h), "ang": 3 if i % 2 else -3, "at": 0.45})
    return scenes

def make(n):
    return Video(n, T[n], AUD + f"v{n}.mp3", fill(SC[n]), OUT + f"oksana_slide_{n}.mp4")

